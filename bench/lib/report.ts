// Result types and the RESULTS.md renderer.

import { IMPLS, IMPL_LABELS } from "./workloads.ts";
import type { Codec, Impl, Op } from "./workloads.ts";
import type { RunStats, Summary } from "./stats.ts";

export interface OpResult extends Summary {
	op: Op;
	impl: Impl;
	runs: RunStats[];
}

export interface WorkloadResult {
	name: string;
	payloadBytes: number;
	blocks: number;
	codec: Codec;
	fileBytes: Partial<Record<Impl, number>>;
	results: OpResult[];
}

export interface Environment {
	cpuModel: string;
	logicalCores: number;
	totalMemoryBytes: number;
	kernel: string;
	os: string | null;
	node: string;
	cc: string;
	cxx: string;
	go?: string;
}

export interface ProfileSummary {
	impl: string;
	workload: string;
	op: string;
	tool: string;
	totalSamplesOrMs: number;
	unit: string;
	top: { name: string; selfPercent: number }[];
}

export interface Results {
	mode: "full" | "quick";
	repeats: number;
	environment: Environment;
	workloads: WorkloadResult[];
	profiles: ProfileSummary[];
}

export interface ReportInput {
	results: Results;
	impls: Impl[];
	reference: Impl;
	commands: string[];
}

export const GENERATED_MARKER = "<!-- Generated by bench/run.ts. Do not edit by hand; run the benchmark again instead. -->";

function cell(s: string): string {
	return s.replace(/\|/g, "\\|").replace(/\n/g, " ");
}

export function renderTable(headers: string[], rows: string[][], rightAlignFrom = 1): string {
	for (const r of rows) {
		if (r.length !== headers.length) throw new Error(`table row has ${r.length} cells, header has ${headers.length}`);
	}
	const sep = headers.map((_, i) => (i >= rightAlignFrom ? "---:" : "---"));
	const line = (cells: string[]): string => `| ${cells.map(cell).join(" | ")} |`;
	return [line(headers), `|${sep.join("|")}|`, ...rows.map(line)].join("\n");
}

export function formatRatio(value: number, reference: number): string {
	if (reference <= 0) return "ref 0";
	const r = value / reference;
	const two = r.toFixed(2);
	return `${r < 1 && two !== "1.00" ? two : r.toFixed(1)}x`;
}

export function withRatio(text: string, value: number, reference: number, isReference: boolean): string {
	return isReference ? text : `${text} (${formatRatio(value, reference)})`;
}

export function formatMiB(kb: number): string {
	return (kb / 1024).toFixed(1);
}

function find(w: WorkloadResult, op: Op, impl: Impl): OpResult {
	const r = w.results.find((x) => x.op === op && x.impl === impl);
	if (r === undefined) throw new Error(`no result for ${w.name} / ${op} / ${impl}`);
	return r;
}

function opsOf(w: WorkloadResult): Op[] {
	const ops: Op[] = [];
	for (const r of w.results) if (!ops.includes(r.op)) ops.push(r.op);
	return ops;
}

// One row per (workload, operation), one column per implementation.
export function metricTable(input: ReportInput, value: (r: OpResult) => number, text: (r: OpResult) => string, ratio: boolean): string {
	const impls = IMPLS.filter((i) => input.impls.includes(i));
	const rows: string[][] = [];
	for (const w of input.results.workloads) {
		for (const op of opsOf(w)) {
			const ref = find(w, op, input.reference);
			rows.push([`${w.name} / ${op}`, ...impls.map((i) => {
				const r = find(w, op, i);
				return ratio ? withRatio(text(r), value(r), value(ref), i === input.reference) : text(r);
			})]);
		}
	}
	return renderTable(["Workload / operation", ...impls.map((i) => IMPL_LABELS[i])], rows);
}

function formatBytes(n: number): string {
	return n.toLocaleString("en-US");
}

function renderEnvironment(e: Environment): string {
	const items = [
		`CPU: ${e.cpuModel}, ${e.logicalCores} logical cores`,
		`Memory: ${(e.totalMemoryBytes / 1024 ** 3).toFixed(1)} GiB`,
		`OS: ${e.os ?? "unknown (no /etc/os-release)"}, kernel ${e.kernel}`,
		`Node: ${e.node}`,
		`cc: ${e.cc}`,
		`c++: ${e.cxx}`,
	];
	if (e.go !== undefined) items.push(`Go CLI: ${e.go}`);
	return items.map((s) => `- ${s}`).join("\n");
}

export function renderProfiles(profiles: ProfileSummary[]): string {
	if (profiles.length === 0) return "";
	const parts = ["## Profiles"];
	for (const p of profiles) {
		const label = (IMPLS as readonly string[]).includes(p.impl) ? IMPL_LABELS[p.impl as Impl] : p.impl;
		parts.push(`### ${label}: ${p.workload} / ${p.op}`);
		parts.push(`${p.tool}, ${p.totalSamplesOrMs} ${p.unit} in total.`);
		parts.push(renderTable(["Function", "Self %"], p.top.map((t) => [`\`${t.name}\``, t.selfPercent.toFixed(1)])));
	}
	return parts.join("\n\n") + "\n";
}

export function renderReport(input: ReportInput): string {
	const { results } = input;
	const impls = IMPLS.filter((i) => input.impls.includes(i));
	const codecWorkloads = results.workloads.filter((w) => w.codec !== "none");
	const parts = [
		GENERATED_MARKER,
		"# binpazer benchmark results",
		`Mode: ${results.mode}, ${results.repeats} timed run(s) per operation. Reference implementation: ${IMPL_LABELS[input.reference]}; ratios in parentheses are relative to it.`,
		"## Environment",
		renderEnvironment(results.environment),
		"## How to reproduce",
		"```sh\n" + input.commands.join("\n") + "\n```",
		"## CPU time (user + sys, median, seconds)",
		metricTable(input, (r) => r.cpuS, (r) => r.cpuS.toFixed(3), true),
		"## Peak memory (max RSS, median, MiB)",
		metricTable(input, (r) => r.maxRssKb, (r) => formatMiB(r.maxRssKb), true),
		"## Wall time and throughput (median)",
		metricTable(input, (r) => r.wallS, (r) => `${r.wallS.toFixed(3)} s, ${Math.round(r.throughputMiBs)} MiB/s`, false),
	];
	if (codecWorkloads.length > 0) {
		parts.push("## Written file size (bytes)");
		parts.push(renderTable(["Workload", ...impls.map((i) => IMPL_LABELS[i])], codecWorkloads.map((w) => [w.name, ...impls.map((i) => {
			const n = w.fileBytes[i];
			if (n === undefined) throw new Error(`no file size for ${w.name} / ${i}`);
			return formatBytes(n);
		})])));
	}
	parts.push("## Notes");
	parts.push([
		"- CPU time is user + sys of the whole process, including runtime start-up.",
		"- Max RSS is the kernel's ru_maxrss for the process.",
		"- Read, stream and find all read the file that the reference implementation wrote.",
		"- Throughput is logical (decoded) bytes divided by the median wall time.",
		"- Compressed file sizes can differ because encoder output is implementation-defined. Every implementation decodes every other implementation's file to the same result.",
		"- For codec none and stored, the files that every implementation writes are byte-identical.",
	].join("\n"));
	let out = parts.join("\n\n") + "\n";
	if (results.profiles.length > 0) out += "\n" + renderProfiles(results.profiles);
	return out;
}
